function pickQuestions(seed, count) {
  const list = QUESTION_BANK.map((item, idx) => ({ ...item, id: idx + 1 }));
  let s = seed;
  const rand = () => {
    s = (s * 16807 + 11) % 2147483647;
    return s / 2147483647;
  };
  const copy = [...list];
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rand() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy.slice(0, count).map((item, i) => ({ ...item, no: i + 1 }));
}

